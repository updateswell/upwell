import type {
  ApplyMode,
  DecisionKind,
  InstallSource,
  Platform,
  RecommendedReason,
  RequiredReason,
  StoreFlow,
  StoreFlowResult,
  TargetVersion,
} from './types';

/**
 * Fields every event carries. Nothing personal: no device or user ids, only the random
 * per-install `installationId`. Install fields are null until the device was read.
 */
export interface UpwellEventBase {
  /** Epoch ms. */
  timestamp: number;
  /** Version of the `upwell` package. */
  sdkVersion: string;
  platform: Platform;
  /** versionName / CFBundleShortVersionString. */
  appVersion: string | null;
  /** versionCode / CFBundleVersion. */
  build: string | null;
  runtimeVersion: string | null;
  /** The running OTA update; null for the embedded bundle. */
  updateId: string | null;
  installSource: InstallSource | null;
  /** Random per-install id generated by the native module. A reinstall gets a new one. */
  installationId: string | null;
  /** The `simulate()` scenario, or null on the real device. Filter these out of dashboards. */
  simulation: string | null;
}

/** Where the policy a check used came from: just fetched, the last known good copy, or none. */
export type PolicyOrigin = 'fresh' | 'cached' | 'none';

/** The decisions that show a store prompt. Prompt caps and snoozes apply to these. */
export type PromptDecisionKind = 'store.recommended' | 'store.required';

/** What the user did with a store prompt. `dismiss`: declined the store's own dialog (Play). */
export type PromptAction = 'update' | 'later' | 'dismiss';

export type UpwellEventFields =
  | {
      /** A check completed (throttled checks that return the current decision don't count). */
      type: 'check';
      decision: DecisionKind;
      /** The decision's reason (`newerVersion`, `stranded`, …, or the error), else null. */
      reason: string | null;
      policy: PolicyOrigin;
      durationMs: number;
    }
  | {
      /** A store prompt is due: first time per decision kind and target per session. */
      type: 'prompt_shown';
      decision: PromptDecisionKind;
      reason: RecommendedReason | RequiredReason;
      flow: StoreFlow;
      target: TargetVersion;
    }
  | {
      type: 'prompt_action';
      action: PromptAction;
      decision: PromptDecisionKind;
      target: TargetVersion;
    }
  | {
      /** A store flow finished. A Play flow that falls back to the store link reports both. */
      type: 'store_flow';
      flow: StoreFlow;
      result: StoreFlowResult;
    }
  | {
      /** An OTA update finished downloading. */
      type: 'ota_downloaded';
      /** Id of the downloaded update, when the OTA adapter reports one. */
      newUpdateId: string | null;
    }
  | {
      /** A restart into the downloaded OTA update was requested. */
      type: 'ota_applied';
      newUpdateId: string | null;
      /** The decision's apply mode (`prompt`: the user tapped restart), or null outside `ota.ready`. */
      applyMode: ApplyMode | null;
    }
  | {
      /** The "Updated" sheet was closed, or `markUpdateSeen()` called, after an OTA update. */
      type: 'updated_seen';
      /** releases.json id of the update. */
      releaseId: string;
    }
  | {
      /** Anything passed to `onError`. */
      type: 'error';
      context: string;
      message: string;
    };

/** One update event, as passed to `onEvent`. Narrow on `type`. */
export type UpwellEvent = UpwellEventBase & UpwellEventFields;

export type UpwellEventType = UpwellEvent['type'];
